#include<stdio.h>
int main(){
	int num1 = 20;
	printf("Number is : %d\n",num1);
	
	float num2 = 89.9;
	printf("Number is : %f\n",num2);

	double num3 = 345.789;
	printf("Number is : %lf\n",num3);
	
	char letter='P';
	printf("Letter is : %c\n",letter);

	char name[6]="Prachi";
	printf("Name is : %s\n",name);
		
	return 0;
	
}
